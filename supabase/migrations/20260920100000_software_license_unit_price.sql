-- ตาราง software_licenses เดิมไม่มีคอลัมน์เกี่ยวกับเงินเลย (ดู 20260814100000_assets.sql:307)
-- การ์ดนี้จึงทำไม่ได้มาตลอด และเคยถูกเว้นไว้อย่างตั้งใจ เพราะการใส่ตัวเลขเงินที่ระบบไม่รู้จริง
-- ลงไปในหน้าที่ผู้บริหารใช้ตัดสินใจต่ออายุสัญญา อันตรายกว่าการไม่มีการ์ดนั้น
--
-- ตั้งชื่อ unit_price ให้ตรงกับ inventory_items.unit_price ที่มีอยู่แล้ว และเป็น numeric เปล่า
-- ไม่มีคอลัมน์สกุลเงิน ตามแบบ contracts.contract_value — ทั้งระบบใช้บาทอย่างเดียว
--
-- nullable โดยตั้งใจ ไม่ใส่ default 0 เพราะ "ยังไม่ได้กรอกราคา" กับ "ของฟรี" ต้องแยกออกจากกัน
-- ถ้าใช้ 0 แทนค่าว่าง การ์ดสรุปจะรวมลิขสิทธิ์ที่ยังไม่รู้ราคาเข้าไปเป็นศูนย์บาท แล้วรายงาน
-- ตัวเลขที่ต่ำกว่าความจริงโดยไม่มีใครรู้ตัว ฝั่งที่คำนวณต้องนับเฉพาะแถวที่มีราคาและบอกจำนวน
-- แถวที่ยังไม่มีราคาให้ผู้อ่านเห็นเสมอ
-- ============================================================================

alter table public.software_licenses
  add column unit_price numeric
    check (unit_price is null or unit_price >= 0);

comment on column public.software_licenses.unit_price is
  'ราคาต่อหนึ่งสิทธิ์ตลอดรอบสัญญา (บาท) — null = ยังไม่ได้บันทึกราคา ไม่ใช่ของฟรี';
