/**
 * ทำให้คำค้นจากผู้ใช้ปลอดภัยก่อนนำไปต่อเป็นสตริงตัวกรองของ PostgREST (`.or('a.ilike.%x%,b.ilike.%x%')`)
 *
 * PostgREST แยกเงื่อนไขใน `.or()` ด้วยจุลภาคและจัดกลุ่มด้วยวงเล็บ ส่วน `%` กับ `_` เป็นไวลด์การ์ดของ
 * SQL LIKE และ `\` เป็นตัว escape ของ LIKE ถ้าปล่อยอักขระเหล่านี้ผ่านไปตรง ๆ ผู้ใช้ที่พิมพ์ชื่อบริษัท
 * ว่า "ก, ข" จะได้ HTTP 400 กลับมาแทนผลค้นหา (พบจริงตอน Pre-production QA audit 2026-08-13) และคำค้น
 * ที่มี `%` จะกลายเป็นไวลด์การ์ดโดยที่ผู้ใช้ไม่ได้ตั้งใจ
 *
 * แทนที่ด้วยช่องว่างแทนการลบทิ้ง เพื่อไม่ให้คำสองคำติดกันเป็นคำเดียว แล้วยุบช่องว่างซ้ำให้เหลือตัวเดียว
 * คืนค่าเป็นสตริงว่างได้ ผู้เรียกต้องตรวจก่อนใช้ (สตริงว่าง = ไม่ต้องใส่ตัวกรองค้นหา)
 */
export function cleanSearch(value: string): string {
  return value
    .replace(/[%_\\,()"]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}
