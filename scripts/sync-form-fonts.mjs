import { readFile, writeFile } from 'node:fs/promises';

// Keep offline document/PDF fonts identical to the locally bundled UI fonts.
const styles = [
  ['regular', 400, 'normal'],
  ['bold', 700, 'normal'],
  ['italic', 400, 'italic'],
  ['bold-italic', 700, 'italic'],
];
const faces = [];
for (const [name, weight, style] of styles) {
  const file = new URL(`../apps/web/src/assets/fonts/th-sarabun-new-${name}.woff`, import.meta.url);
  const data = (await readFile(file)).toString('base64');
  faces.push(`@font-face{font-family:FormThai;font-style:${style};font-weight:${weight};font-display:swap;src:url(data:font/woff;base64,${data}) format("woff");}`);
}
const header = '// TH Sarabun New, GPL 2.0 or later with font exception. See fonts/TH-Sarabun-New-LICENSE.txt.\n'
  + '// Generated by scripts/sync-form-fonts.mjs; FormThai is the legacy document alias.\n';
await writeFile(new URL('../packages/shared/src/formFont.ts', import.meta.url), `${header}export const FORM_FONT_CSS = ${JSON.stringify(faces.join(''))};\n`);
